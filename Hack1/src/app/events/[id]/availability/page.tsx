'use client';

import React, { useState, Suspense } from 'react';
import Link from 'next/link';
import { useParams } from 'next/navigation';
import { store } from '@/lib/store';
import { toast } from '@/lib/toast';
import { AppShell } from '@/components/AppShell';
import { SanitizedText } from '@/components/SanitizedText';
import { proposeMeetingSlots } from '@/lib/agents/meetingTimeAgent';
import { hasPermission } from '@/lib/permissions';
import {
  Calendar,
  Clock,
  Sparkles,
  CheckCircle2,
  AlertCircle,
  HelpCircle,
  ShieldCheck,
  ArrowLeft,
  FileText,
  UserCheck,
  Send,
} from 'lucide-react';
import { AvailabilityResponse } from '@/types';

function EventAvailabilityContent() {
  const params = useParams();
  const eventId = params?.id as string;

  const currentOrg = store.getCurrentOrg();
  const currentUser = store.getCurrentUser();
  const { role } = store.getCurrentMembership();
  const [isChatOpen, setIsChatOpen] = useState(false);

  const [myReason, setMyReason] = useState('');
  const [reportCopied, setReportCopied] = useState(false);

  const event = store.getEvent(eventId);
  if (!event || !currentOrg || !currentUser) {
    return (
      <div style={{ padding: '2rem', textAlign: 'center' }}>
        <p>Event not found.</p>
        <Link href="/events">Back to Events</Link>
      </div>
    );
  }

  // Meeting Time Agent Proposals
  const aiProposals = proposeMeetingSlots(eventId);

  // Availability records
  const availabilityList = store.getEventAvailability(eventId);
  const eventMembers = store.getEventMembers(eventId);

  const myRsvp = availabilityList.find((a) => a.userId === currentUser.id);

  const handleUpdateRsvp = (status: AvailabilityResponse['status'], reason = '') => {
    store.setMemberAvailability(eventId, currentUser.id, status, reason);
    store.logAction('availability.update', 'event', eventId, { status, reason });
    toast.success(`RSVP updated to ${status.toUpperCase()}!`, 'Availability Updated');
  };

  // Compile complete availability report
  const compileReportText = () => {
    const lines = [
      `AVAILABILITY REPORT FOR: ${event.title}`,
      `Generated by Rally AI Agent`,
      `Event Scheduled: ${new Date(event.startTime).toLocaleString()}`,
      `Location: ${event.location}`,
      `----------------------------------------`,
      `SUMMARY OF RESPONSES:`,
    ];

    eventMembers.forEach((em) => {
      const resp = availabilityList.find((a) => a.userId === em.userId);
      const name = em.user?.fullName || 'Member';
      const status = resp ? resp.status.toUpperCase() : 'PENDING';
      const reason = resp?.reason ? ` (Reason: ${resp.reason})` : '';
      lines.push(`• ${name}: ${status}${reason}`);
    });

    lines.push(`----------------------------------------`);
    lines.push(`AI RECOMMENDATION:`);
    lines.push(aiProposals.summaryNote);

    return lines.join('\n');
  };

  const handleCopyReport = () => {
    navigator.clipboard.writeText(compileReportText());
    setReportCopied(true);
    toast.success('Availability report copied to clipboard!', 'Report Ready to Share');
    setTimeout(() => setReportCopied(false), 2500);
  };

  return (
    <AppShell>
      <div>
        {/* Back Link & Header */}
        <div style={{ marginBottom: '1.5rem' }}>
          <Link
            href="/events"
            style={{
              display: 'inline-flex',
              alignItems: 'center',
              gap: '0.375rem',
              fontSize: '0.875rem',
              color: 'var(--text-secondary)',
              textDecoration: 'none',
              marginBottom: '0.75rem',
            }}
          >
            <ArrowLeft size={16} />
            <span>Back to Events</span>
          </Link>

          <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', gap: '1rem', flexWrap: 'wrap' }}>
            <div>
              <div style={{ display: 'flex', alignItems: 'center', gap: '0.5rem', marginBottom: '0.25rem' }}>
                <h1 style={{ fontSize: '1.75rem', color: 'var(--text-primary)' }}>
                  Availability Control Center
                </h1>
                <span className="badge badge-info">Privacy Protected</span>
              </div>
              <p style={{ fontSize: '0.9375rem', color: 'var(--text-secondary)' }}>
                <SanitizedText>{event.title}</SanitizedText>
              </p>
            </div>

            <button
              type="button"
              onClick={handleCopyReport}
              className="btn btn-secondary"
              style={{ minHeight: '40px' }}
            >
              <FileText size={16} />
              <span>{reportCopied ? 'Report Copied to Clipboard!' : 'Export AI Availability Report'}</span>
            </button>
          </div>
        </div>

        {/* Privacy Notice Banner */}
        <div
          style={{
            padding: '0.875rem 1.25rem',
            borderRadius: '0.5rem',
            backgroundColor: 'var(--bg-surface-elevated)',
            border: '1px solid var(--border-color)',
            display: 'flex',
            alignItems: 'center',
            gap: '0.75rem',
            marginBottom: '1.5rem',
          }}
        >
          <ShieldCheck size={20} color="#10B981" />
          <div style={{ fontSize: '0.8125rem', color: 'var(--text-secondary)' }}>
            <SanitizedText>
              Privacy Shield Active: Organisers only see whether you are Free or Busy. Class names, module codes, and location details are never exposed.
            </SanitizedText>
          </div>
        </div>

        {/* 2-Column Grid */}
        <div
          style={{
            display: 'grid',
            gridTemplateColumns: 'repeat(auto-fit, minmax(320px, 1fr))',
            gap: '1.5rem',
          }}
        >
          {/* Column 1: Meeting Time Agent Recommendations */}
          <div className="card" style={{ padding: '1.5rem' }}>
            <div style={{ display: 'flex', alignItems: 'center', gap: '0.5rem', marginBottom: '1rem' }}>
              <Sparkles size={20} color="var(--brand-primary)" />
              <h2 style={{ fontSize: '1.25rem' }}>Meeting Time Agent</h2>
            </div>

            <p style={{ fontSize: '0.875rem', color: 'var(--text-secondary)', marginBottom: '1.25rem', lineHeight: 1.5 }}>
              <SanitizedText>
                The AI has evaluated all member timetables to rank the optimal meeting times with highest team attendance.
              </SanitizedText>
            </p>

            <div style={{ display: 'flex', flexDirection: 'column', gap: '0.875rem', marginBottom: '1.25rem' }}>
              {aiProposals.proposals.map((slot, idx) => (
                <div
                  key={idx}
                  style={{
                    padding: '1rem',
                    borderRadius: '0.5rem',
                    backgroundColor: idx === 0 ? 'var(--brand-primary-subtle)' : 'var(--bg-surface-elevated)',
                    border: idx === 0 ? '2px solid var(--border-focus)' : '1px solid var(--border-color)',
                  }}
                >
                  <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '0.375rem' }}>
                    <span style={{ fontWeight: 700, fontSize: '0.9375rem', color: 'var(--text-primary)' }}>
                      #{idx + 1} {slot.dayName} ({slot.timeWindow})
                    </span>
                    <span
                      className={`badge ${
                        slot.percentage >= 75 ? 'badge-success' : 'badge-warning'
                      }`}
                    >
                      {slot.percentage}% Free
                    </span>
                  </div>

                  <div style={{ fontSize: '0.8125rem', color: 'var(--text-secondary)' }}>
                    <SanitizedText>{slot.recommendationNote}</SanitizedText>
                  </div>
                </div>
              ))}
            </div>

            <div
              style={{
                padding: '0.75rem',
                borderRadius: '0.5rem',
                backgroundColor: 'var(--bg-surface-elevated)',
                fontSize: '0.8125rem',
                color: 'var(--text-muted)',
              }}
            >
              <SanitizedText>{aiProposals.summaryNote}</SanitizedText>
            </div>
          </div>

          {/* Column 2: Roster Availability & Personal RSVP */}
          <div className="card" style={{ padding: '1.5rem' }}>
            <h2 style={{ fontSize: '1.25rem', marginBottom: '1rem' }}>My Attendance Response</h2>

            <div
              style={{
                padding: '1rem',
                borderRadius: '0.5rem',
                backgroundColor: 'var(--bg-surface-elevated)',
                border: '1px solid var(--border-color)',
                marginBottom: '1.5rem',
              }}
            >
              <div style={{ fontSize: '0.875rem', color: 'var(--text-primary)', marginBottom: '0.75rem' }}>
                Your current status:{' '}
                <strong style={{ color: 'var(--brand-primary-text)' }}>
                  {myRsvp ? myRsvp.status.toUpperCase() : 'PENDING RSVP'}
                </strong>
                {myRsvp?.reason && <span> (Reason: {myRsvp.reason})</span>}
              </div>

              <div style={{ display: 'flex', gap: '0.5rem', flexWrap: 'wrap', marginBottom: '0.75rem' }}>
                <button
                  type="button"
                  onClick={() => handleUpdateRsvp('confirmed')}
                  className="btn btn-primary"
                  style={{ minHeight: '38px', fontSize: '0.8125rem' }}
                >
                  <CheckCircle2 size={16} />
                  <span>I am Available</span>
                </button>
                <button
                  type="button"
                  onClick={() => handleUpdateRsvp('tentative', myReason || 'Tentative schedule')}
                  className="btn btn-secondary"
                  style={{ minHeight: '38px', fontSize: '0.8125rem' }}
                >
                  <HelpCircle size={16} />
                  <span>Tentative</span>
                </button>
                <button
                  type="button"
                  onClick={() => handleUpdateRsvp('unavailable', myReason || 'Unavailable')}
                  className="btn btn-danger"
                  style={{ minHeight: '38px', fontSize: '0.8125rem' }}
                >
                  <AlertCircle size={16} />
                  <span>Unavailable</span>
                </button>
              </div>

              <input
                type="text"
                placeholder="Optional reason for tentative/unavailable status"
                value={myReason}
                onChange={(e) => setMyReason(e.target.value)}
                style={{ minHeight: '36px', fontSize: '0.8125rem' }}
              />
            </div>

            {/* Complete Member RSVP Roster */}
            <div>
              <div style={{ fontWeight: 700, fontSize: '0.875rem', color: 'var(--text-primary)', marginBottom: '0.75rem' }}>
                Event Roster Responses ({eventMembers.length} members)
              </div>

              <div style={{ display: 'flex', flexDirection: 'column', gap: '0.5rem' }}>
                {eventMembers.map((em) => {
                  const resp = availabilityList.find((a) => a.userId === em.userId);
                  const isFree = resp?.status === 'confirmed' || resp?.status === 'free';
                  const isTentative = resp?.status === 'tentative';
                  const isUnavailable = resp?.status === 'unavailable';

                  return (
                    <div
                      key={em.id}
                      style={{
                        padding: '0.75rem',
                        borderRadius: '0.5rem',
                        backgroundColor: 'var(--bg-surface-elevated)',
                        border: '1px solid var(--border-color)',
                        display: 'flex',
                        alignItems: 'center',
                        justifyContent: 'space-between',
                      }}
                    >
                      <div>
                        <div style={{ fontWeight: 600, fontSize: '0.875rem' }}>
                          {em.user?.fullName}
                        </div>
                        <div style={{ fontSize: '0.75rem', color: 'var(--text-muted)' }}>
                          Role: {em.eventRole}
                        </div>
                        {resp?.reason && (
                          <div style={{ fontSize: '0.75rem', color: 'var(--badge-warning-text)', marginTop: '0.2rem' }}>
                            Reason: <SanitizedText>{resp.reason}</SanitizedText>
                          </div>
                        )}
                      </div>

                      <span
                        className={`badge ${
                          isFree
                            ? 'badge-success'
                            : isTentative
                            ? 'badge-warning'
                            : isUnavailable
                            ? 'badge-error'
                            : 'badge-info'
                        }`}
                        style={{ fontSize: '0.6875rem' }}
                      >
                        {resp ? resp.status : 'PENDING'}
                      </span>
                    </div>
                  );
                })}
              </div>
            </div>
          </div>
        </div>
      </div>
    </AppShell>
  );
}

export default function EventAvailabilityPage() {
  return (
    <Suspense fallback={<div style={{ padding: '2rem', textAlign: 'center' }}>Loading Availability Center...</div>}>
      <EventAvailabilityContent />
    </Suspense>
  );
}
